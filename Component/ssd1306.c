// Вывод строки
void OLED_WriteString_light(uint8_t update_src, OLED_HandleTypeDef *oled, uint16_t row, uint16_t col, char *str) {

    OLED_SetTextCursor(oled, row, col);
    int i = 0;
    while (str[i]) {
        OLED_WriteChar(oled, str[i++]);
    }
}

// Перевернуть экран по горизонтали
void OLED_FlipHorizontal(OLED_HandleTypeDef *oled, uint8_t flip) {
    if (flip) {
        OLED_WriteCommand(oled, 0xA0); // Seg re-map: column address 0 mapped to SEG0
    } else {
        OLED_WriteCommand(oled, 0xA1); // Seg re-map: column address 127 mapped to SEG0
    }
}

// Перевернуть экран по вертикали
void OLED_FlipVertical(OLED_HandleTypeDef *oled, uint8_t flip) {
    if (flip) {
        OLED_WriteCommand(oled, 0xC0); // COM output scan direction: normal mode
    } else {
        OLED_WriteCommand(oled, 0xC8); // COM output scan direction: remapped mode
    }
}

// Установка позиции текста (строка 0-3, столбец 0-25)
void OLED_SetTextCursor(OLED_HandleTypeDef *oled, uint16_t row, uint16_t col) {
    oled->currentX = col * (FONT_WIDTH + 1);
    oled->currentY = row * 8; // 8 пикселей на строку
}

// Инвертировать цвета дисплея
void OLED_InvertColors(OLED_HandleTypeDef *oled, uint8_t invert) {
    if (invert) {
        OLED_WriteCommand(oled, 0xA7); // Inverted display
    } else {
        OLED_WriteCommand(oled, 0xA6); // Normal display
    }
}
/**
 * @brief копирование в буфер с поворотом
 * 
 * @param oled структура содержащяя исходный буфер
 * @param lcd_mem копия буфера с поворотом 
 * @param mem_rotate поворот в памяти на 90, 180, 270
 */
void Copy_oled_mem(OLED_HandleTypeDef* oled, void* lcd_mem, int mem_rotate){
    //uint16_t* lcd_buffer565 = (uint16_t*)lcd_mem; //для цвета565 хорошо подходит uint16_t* указатель
    RGB888_Pixel* lcd_buffer888 = (RGB888_Pixel*)lcd_mem;
    uint8_t* mono_buffer = (uint8_t*)&oled->buffer;
    
    
    int offset_x = (REAL_HEIGHT - OLED_HEIGHT) / 2; //
    int offset_y = (REAL_WIDTH - OLED_WIDTH) / 2;  //
    
    // Копируем монохромное изображение в центр LCD
    for (int y = 0; y < OLED_HEIGHT; y++) {
        for (int x = 0; x < OLED_WIDTH; x++) {
            // Получаем значение пикселя из монохромного буфера
            int byte_index = x + (y / 8) * OLED_WIDTH;
            int bit_index = y % 8;
            int pixel_value = (mono_buffer[byte_index] >> bit_index) & 0x01;

            int rotated_x = 0;
            int rotated_y = 0;

            //TO DO разобраться с поворотом на 180
            if(mem_rotate == 0){
                rotated_x = OLED_HEIGHT - 1 - y; // 0-31
                rotated_y = x;                   // 0-127  
            }else if(mem_rotate == 1){
                rotated_x = y;                 //(бывшая высота становится шириной)
                rotated_y = OLED_WIDTH -1- x;    // (бывшая ширина становится высотой, перевернутой)
            }else if(mem_rotate == 2){
                rotated_x = OLED_WIDTH -1- x;  // 0-127  
                rotated_y = OLED_HEIGHT -1- y; // 0-31
            }else{
                rotated_x = x; // 0-31
                rotated_y = y;               // 0-127
            }
            
            int lcd_x = rotated_x + offset_x;
            int lcd_y = rotated_y + offset_y;
            
            //Копирование и установка цвета пикселя в RGB565
            if (lcd_x < OLED_HEIGHT && lcd_y < OLED_WIDTH) {
                //lcd_buffer565[lcd_y * OLED_HEIGHT + lcd_x] = pixel_value ? 0x0000 : 0xFFFF;
                size_t index = lcd_y * OLED_HEIGHT + lcd_x;
                if (pixel_value) {
                    lcd_buffer888[index].r = 0x00;
                    lcd_buffer888[index].g = 0x00;
                    lcd_buffer888[index].b = 0x00;
                } else {
                    lcd_buffer888[index].r = 0xFF;
                    lcd_buffer888[index].g = 0xFF;
                    lcd_buffer888[index].b = 0xFF;
                }
            }
        }
    }
}